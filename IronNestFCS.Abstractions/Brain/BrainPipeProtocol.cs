using System.IO.Pipes;
using System.Text;
using System.Text.Json;
using System.Text.Json.Serialization;

namespace IronNestFCS.Abstractions.Brain;

public sealed record BrainPipeRequest(
    string Type,
    string ProtocolVersion = BrainPipeProtocol.CurrentVersion,
    string? EpisodeId = null,
    string? DecisionId = null,
    BrainActionKind? ActionKind = null,
    string? TrackId = null,
    int TimeoutMs = 5000,
    string? Payload = null);

public sealed record BrainPipeResponse(
    string Type,
    string ProtocolVersion,
    string? EpisodeId = null,
    string? DecisionId = null,
    bool Accepted = true,
    BrainActionKind? ActionKind = null,
    string? TrackId = null,
    string? Error = null,
    string? Payload = null)
{
    public static BrainPipeResponse Pong() => new("pong", BrainPipeProtocol.CurrentVersion);

    public static BrainPipeResponse ErrorResponse(string error)
    {
        return new("error", BrainPipeProtocol.CurrentVersion, Accepted: false, Error: error);
    }

    public static BrainPipeResponse HoldFallback(string reason)
    {
        return new(
            "action",
            BrainPipeProtocol.CurrentVersion,
            Accepted: false,
            ActionKind: BrainActionKind.Hold,
            Error: reason);
    }
}

/// <summary>
/// Newline-delimited JSON protocol. It is deliberately independent of the
/// Brain observation internals; Payload can carry a versioned DTO generated by
/// the facade adapter without making the pipe thread understand Unity types.
/// </summary>
public static class BrainPipeProtocol
{
    public const string CurrentVersion = "1";

    private static readonly JsonSerializerOptions JsonOptions = new()
    {
        PropertyNameCaseInsensitive = true,
        Converters = { new JsonStringEnumConverter() },
    };

    public static string Encode(BrainPipeRequest request)
    {
        ArgumentNullException.ThrowIfNull(request);
        return JsonSerializer.Serialize(request, JsonOptions);
    }

    public static string Encode(BrainPipeResponse response)
    {
        ArgumentNullException.ThrowIfNull(response);
        return JsonSerializer.Serialize(response, JsonOptions);
    }

    public static BrainPipeResponse DecodeResponse(string line)
    {
        if (string.IsNullOrWhiteSpace(line))
            throw new ArgumentException("response line is empty", nameof(line));
        return JsonSerializer.Deserialize<BrainPipeResponse>(line, JsonOptions)
            ?? throw new InvalidDataException("response is null");
    }

    public static string ProcessLine(
        string? line,
        Func<BrainPipeRequest, BrainPipeResponse?> handler)
    {
        ArgumentNullException.ThrowIfNull(handler);
        if (string.IsNullOrWhiteSpace(line))
            return Encode(BrainPipeResponse.ErrorResponse("empty request"));

        BrainPipeRequest? request;
        try
        {
            request = JsonSerializer.Deserialize<BrainPipeRequest>(line, JsonOptions);
        }
        catch (JsonException exception)
        {
            return Encode(BrainPipeResponse.ErrorResponse($"malformed request: {exception.Message}"));
        }

        if (request == null || string.IsNullOrWhiteSpace(request.Type))
            return Encode(BrainPipeResponse.ErrorResponse("request type is required"));
        if (!string.Equals(request.ProtocolVersion, CurrentVersion, StringComparison.Ordinal))
            return Encode(BrainPipeResponse.ErrorResponse($"unsupported protocol version: {request.ProtocolVersion}"));

        try
        {
            return Encode(handler(request) ?? BrainPipeResponse.HoldFallback("policy handler returned no response"));
        }
        catch (Exception exception)
        {
            // A policy failure must degrade to Hold at the transport boundary;
            // it must never block or crash the game thread.
            return Encode(BrainPipeResponse.HoldFallback($"policy handler failed: {exception.GetType().Name}"));
        }
    }
}

/// <summary>
/// Dedicated synchronous named-pipe worker. The handler must only manipulate
/// pure DTOs; a Unity adapter should enqueue the request for its main-thread
/// Update loop and return a safe response when the policy times out.
/// </summary>
public sealed class NamedPipeBrainServer : IDisposable
{
    private static readonly Encoding Utf8NoBom = new UTF8Encoding(encoderShouldEmitUTF8Identifier: false);
    private readonly string pipeName;
    private readonly Func<BrainPipeRequest, BrainPipeResponse?> handler;
    private readonly object sync = new();
    private Thread? worker;
    private NamedPipeServerStream? activePipe;
    private volatile bool stopping;

    public NamedPipeBrainServer(
        string pipeName,
        Func<BrainPipeRequest, BrainPipeResponse?> handler)
    {
        if (string.IsNullOrWhiteSpace(pipeName))
            throw new ArgumentException("pipe name is required", nameof(pipeName));
        this.pipeName = pipeName;
        this.handler = handler ?? throw new ArgumentNullException(nameof(handler));
    }

    public bool IsStopped => worker == null || !worker.IsAlive;

    public void Start()
    {
        lock (sync)
        {
            if (worker is { IsAlive: true })
                return;
            stopping = false;
            worker = new Thread(Run)
            {
                IsBackground = true,
                Name = "IronNest Brain NamedPipe",
            };
            worker.Start();
        }
    }

    public void Stop()
    {
        stopping = true;
        lock (sync)
        {
            activePipe?.Dispose();
        }
        // A synchronous WaitForConnection is not guaranteed to unblock when
        // the server stream is disposed from another thread on Windows. A
        // short-lived local client connection wakes that wait deterministically.
        try
        {
            using var wake = new NamedPipeClientStream(".", pipeName, PipeDirection.Out, PipeOptions.None);
            wake.Connect(250);
        }
        catch (IOException)
        {
        }
        catch (TimeoutException)
        {
        }
        var current = worker;
        if (current != null && current != Thread.CurrentThread)
            current.Join(TimeSpan.FromSeconds(2));
    }

    public void Dispose() => Stop();

    private void Run()
    {
        while (!stopping)
        {
            using var pipe = new NamedPipeServerStream(
                pipeName,
                PipeDirection.InOut,
                1,
                PipeTransmissionMode.Byte,
                PipeOptions.None);
            lock (sync)
                activePipe = pipe;

            try
            {
                pipe.WaitForConnection();
                if (stopping)
                    return;
                using var reader = new StreamReader(pipe, Utf8NoBom, detectEncodingFromByteOrderMarks: false, bufferSize: 1024, leaveOpen: true);
                using var writer = new StreamWriter(pipe, Utf8NoBom, bufferSize: 1024, leaveOpen: true)
                {
                    AutoFlush = true,
                };
                // One request per connection keeps stop/disconnect semantics
                // deterministic for a small control protocol. A client can
                // reconnect for the next decision without holding the worker
                // on an unbounded ReadLine.
                var line = reader.ReadLine();
                if (!stopping && line != null)
                    writer.WriteLine(BrainPipeProtocol.ProcessLine(line, handler));
            }
            catch (IOException) when (stopping)
            {
                // Stop() closes the pipe to release WaitForConnection/ReadLine.
            }
            catch (ObjectDisposedException) when (stopping)
            {
            }
            finally
            {
                lock (sync)
                {
                    if (ReferenceEquals(activePipe, pipe))
                        activePipe = null;
                }
            }
        }
    }
}
